export const FILIERES = Object.keys(COURS).filter((f) => f !== "Tronc commun");

export const ANNEES = [
  ...new Set(Object.values(COURS).flatMap((annees) => Object.keys(annees))),
];

//ignnorer les accents et majuscules pour la vérification
const norm = (s: string) =>
  s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[’‘]/g, "'")
    .trim();

export function verifierContexte(ctx: {
  cours?: string | null;
  filiere?: string | null;
  annee?: string | null;
}): string | null {
  const { cours, filiere, annee } = ctx;

  if (filiere && !FILIERES.some((f) => norm(f) === norm(filiere)))
    return `Filière inconnue : ${filiere}`;
  if (annee && !ANNEES.some((a) => norm(a) === norm(annee)))
    return `Année inconnue : ${annee}`;
  if (!cours) return null; // rien à vérifier de plus

  const trouve = Object.entries(COURS).some(
    ([nomFiliere, annees]) =>
      (nomFiliere === "Tronc commun" || !filiere || norm(nomFiliere) === norm(filiere)) &&
      Object.entries(annees).some(
        ([a, liste]) =>
          (!annee || norm(a) === norm(annee)) &&
          liste.some((c) => norm(c) === norm(cours))
      )
  );

  return trouve ? null : `Le cours « ${cours} » n'existe pas pour cette filière ou cette année`;
}